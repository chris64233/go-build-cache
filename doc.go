// Package buildcache 实现内容寻址的构建缓存服务。
//
// 核心模型：
//   - 缓存值在创建上传会话时即被拆分为若干不可变的内容块（chunk），每个块以其
//     SHA-256 摘要作为身份，存入内容寻址存储（CAS），可被不同会话/条目共享。
//   - 分片允许乱序上传、允许相同内容重传；同一片号上传不同内容属于幂等冲突。
//   - 只有 Complete 校验（分片齐全、总大小、最终摘要）通过并原子发布后，条目才对读者可见。
//   - 会话带租约（lease），过期判断统一使用注入的 Clock。
//   - 垃圾回收采用 标记 -> 屏障等待在途发布 -> 重新标记并清扫 的两阶段方式，
//     并为每个内容块留下可审计的决策记录。
